export function getCountryOptions(locale: string): SelectOption[] {
  if (locale === defaultLocale || typeof Intl.DisplayNames === "undefined")
    return countryOptions;
  const displayNames = new Intl.DisplayNames([locale], { type: "region" });
  return countryOptions.map(({ code, ...option }) => {
    const label = displayNames.of(code);
    return { ...option, label: label && label !== code ? label : option.label };
  });
}
